import { AGENT_GUIDE_PATH, API_DOCS_PATH, OPENAPI_PATH } from "./docs-paths.js";

/**
 * The agent entry point served at `/llms.txt` (KTK-155). It is a plain-text map
 * of the published surface: what kticket is, where the contract lives, and the
 * rules a machine must know. It never grants access a person does not have —
 * identity is the wallet, and every client uses the same endpoints.
 */
export function llmsTxt(origin: string, network: string): string {
  // Keep path templates readable: `new URL` would percent-encode the braces.
  const base = origin.replace(/\/+$/, "");
  const link = (path: string) => `${base}${path}`;

  return [
    "# kticket",
    "",
    "> kticket sells event tickets on Kaspa. The HTTP API is the product; the",
    "> browser app is one client of it. There is no agent-specific account or",
    "> token: if a person can do it, a machine can do it the same way.",
    "",
    "Identity is wallet ownership. Sign a server-issued challenge and every",
    "request is scoped to that wallet. The server reports its network; never",
    "choose one yourself.",
    "",
    "## Contract",
    "",
    `- [HTTP API reference](${link(API_DOCS_PATH)}): every endpoint, schema, example, and error code.`,
    `- [Agent guide](${link(AGENT_GUIDE_PATH)}): signing, the two-step prepare/finalize flow, and the rules as markdown.`,
    `- [OpenAPI document](${link(OPENAPI_PATH)}): the same contract as OpenAPI 3.1 JSON.`,
    `- \`GET /health\`: \`{ "status": "ok", "network": "${network}" }\`.`,
    "",
    "## Authentication",
    "",
    "The credential is a signature over a single-use challenge.",
    "",
    `1. \`POST ${link("/v1/auth/challenge")}\` with \`{ "address": "kaspa:..." }\`.`,
    "2. Sign the returned `message` verbatim with the wallet's Kaspa private key",
    "   (Schnorr; hex or base64).",
    `3. \`POST ${link("/v1/auth/session")}\` with \`{ "message", "signature" }\`;`,
    "   it returns `{ token, expires_in_seconds }`.",
    "4. Send `Authorization: Bearer <token>` on user-specific reads such as",
    "   `GET /v1/tickets`.",
    "",
    "Public reads (`GET /v1/events`, event detail, listings) need no token.",
    "",
    "## Shareable event pages",
    "",
    "`GET /events/{covenant_id}` is the human page and the link preview: the shell",
    "carries the verified event's title, description, canonical URL, and Open",
    "Graph/Twitter tags. Unknown, unverified, or temporarily unreachable events",
    "still return 200 with the generic site metadata — a preview is never proof.",
    "`GET /sitemap.xml` lists verified event pages and `GET /robots.txt` points",
    "at it; the JSON facts remain at `GET /v1/events/{covenant_id}`.",
    "",
    "## Buying a ticket",
    "",
    "Money moves in two stateless steps:",
    "",
    `- \`POST ${link("/v1/events/{covenant_id}/buy/prepare")}\` with`,
    '  `{ "publicKey": "...", "address": "..." }` returns `buy_id`, the unsigned',
    "  `template`, the safe-JSON `signing_template`, and `sign_inputs`.",
    "- Sign exactly the `sign_inputs` (the server has already prepared the",
    "  covenant spend at input 0), then",
    `  \`POST ${link("/v1/events/{covenant_id}/buy/finalize")}\` with`,
    "  `{ buy_id, template, signed }`. It returns `{ txid }` after the mint is",
    "  confirmed on chain.",
    "",
    "## Publishing an event",
    "",
    `\`POST ${link("/v1/events/deploy/prepare")}\` takes \`capacity\`, \`price_kas\``,
    "(KAS, not sompi), `publicKey`, `address`, and optional KCC-20 metadata;",
    "finalize with `{ deploy_id, template, signed }`. A successful finalize",
    "registers the event for discovery. `POST /v1/events` can register an",
    "already-deployed event by `deploy_txid`.",
    "",
    "## Resale",
    "",
    "`GET /v1/listings` and `GET /v1/events/{covenant_id}/listings` return",
    "chain-proven listings. A holder lists with",
    "`POST /v1/tickets/{ticket_id}/list/prepare` (price in sompi) then",
    "`POST /v1/tickets/{ticket_id}/list/finalize`, and clears it with",
    "`POST /v1/tickets/{ticket_id}/delist/prepare` then",
    "`POST /v1/tickets/{ticket_id}/delist/finalize`. Anyone can buy a listing with",
    "`POST /v1/tickets/{ticket_id}/purchase/prepare` then",
    "`POST /v1/tickets/{ticket_id}/purchase/finalize` — the seller need not be",
    "online.",
    "",
    "## Check-in (door)",
    "",
    "`POST /v1/tickets/{ticket_id}/use/prepare` returns the template the owner",
    "pre-signs plus a `use_id`. The gate rebuilds the same template with",
    "`/use/sign-template`, co-signs input 0, then `/use/finalize` assembles and",
    "broadcasts. A ticket id is `<64-hex-txid>:<output-index>`.",
    "",
    "## Errors",
    "",
    "Every failure uses one envelope:",
    "",
    '`{ "error": { "type": "invalid", "message": "...", "retryable": false } }`',
    "",
    "`type` is stable and machine-readable: `invalid`, `conflict`, `policy`,",
    "`network`, `upstream`, `unauthorized`, or `unknown-*`. `retryable` says",
    "whether the same request may succeed later. HTTP status carries the class:",
    "400 invalid, 401 unauthorized, 404 not found, 409 conflict, 422 rejected by",
    "policy, 502 network refused, 503 upstream unavailable.",
    "",
    "## Safety",
    "",
    "- `prepare` results are correlated by an id but the server keeps no pending",
    "  state: finalize promptly, and do not retry a broadcast blindly.",
    "- Never alter the template between prepare and finalize; the server merges",
    "  signatures into exactly the template it issued.",
    "- Amounts are sompi (1 KAS = 100,000,000 sompi) except `price_kas` on deploy.",
    "",
  ].join("\n");
}
